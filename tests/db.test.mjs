// Database tests: runs supabase/schema.sql on a real Postgres (PGlite) with a
// minimal stand-in for Supabase's auth schema and roles, then checks what each
// role may read and write.   Run:  cd tests && npm install && npm run test:db
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';

const schema = readFileSync(new URL('../supabase/schema.sql', import.meta.url), 'utf8');
let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => { cond ? pass++ : fail++; console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${cond ? '' : '  ' + JSON.stringify(extra)}`); };

// What Supabase provides out of the box (roles, auth.users, auth.uid(), realtime)
const SUPABASE_BASE = `
  create role anon nologin;
  create role authenticated nologin;
  create schema auth;
  create table auth.users (id uuid primary key, email text, raw_user_meta_data jsonb default '{}'::jsonb);
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant usage on schema auth to anon, authenticated;
  grant execute on function auth.uid() to anon, authenticated;
  grant usage on schema public to anon, authenticated;
  alter default privileges in schema public grant all on tables    to anon, authenticated;
  alter default privileges in schema public grant all on sequences to anon, authenticated;
  alter default privileges in schema public grant all on functions to anon, authenticated;
  create publication supabase_realtime;
`;
const U = { admin: 'a0000000-0000-0000-0000-00000000000a', baker: 'b0000000-0000-0000-0000-00000000000b',
            driver: 'd0000000-0000-0000-0000-00000000000d', nobody: 'e0000000-0000-0000-0000-00000000000e' };

async function as(db, who, sql, params) {
  await db.exec('reset role');
  await db.query(`select set_config('request.jwt.claim.sub', $1, false)`, [who ? U[who] : '']);
  await db.exec(`set role ${who ? 'authenticated' : 'anon'}`);
  try { return { rows: (await db.query(sql, params)).rows }; }
  catch (e) { return { error: e.message }; }
  finally { await db.exec('reset role'); }
}

// ═══ A. Upgrade from the first version ═══════════════════════════════════
{
  const db = new PGlite();
  await db.exec(SUPABASE_BASE);
  await db.exec(`
    create table public.profiles (id uuid primary key references auth.users(id) on delete cascade,
      full_name text not null default '', role text not null default 'staff' check (role in ('admin','staff')),
      created_at timestamptz not null default now());
    create table public.stores (id bigint generated by default as identity primary key, name text not null,
      area text not null default '', address text not null default '', seq integer not null default 0,
      archived boolean not null default false, updated_at timestamptz not null default now(), updated_by uuid);
    create table public.products (id bigint generated by default as identity primary key, name text not null,
      icon text not null default '📦', sort integer not null default 0, archived boolean not null default false,
      updated_at timestamptz not null default now(), updated_by uuid);
    create table public.order_items (delivery_date date not null, store_id bigint not null references public.stores(id),
      product_id bigint not null references public.products(id), qty integer not null default 0,
      updated_at timestamptz not null default now(), updated_by uuid, primary key (delivery_date, store_id, product_id));
    alter table public.order_items enable row level security;
    create policy "orders: signed-in users add" on public.order_items for insert to authenticated with check (true);
    insert into auth.users (id, email) values ('${U.driver}', 'old-staff@example.com');
    insert into public.profiles (id, full_name, role) values ('${U.driver}', 'old', 'staff');
    insert into public.stores (id, name, seq) values (1, 'Vatan', 1);
    insert into public.products (id, name) values (1, '6 Pack');
    insert into public.order_items values ('2026-01-05', 1, 1, 4, now(), null);
  `);
  await db.exec(schema);
  await db.exec(schema);
  ok('upgrade: old "staff" user becomes "driver"', (await db.query(`select role from public.profiles where id = '${U.driver}'`)).rows[0].role === 'driver');
  ok('upgrade: old permissive rule removed',
    (await db.query(`select count(*)::int n from pg_policies where policyname = 'orders: signed-in users add'`)).rows[0].n === 0);
  ok('upgrade: new store columns added (route 1, empty contact/phone/ABN)',
    JSON.stringify((await db.query(`select route, contact_name, phone, abn from public.stores where id = 1`)).rows[0])
      === JSON.stringify({ route: 1, contact_name: '', phone: '', abn: '' }));
  ok('upgrade: existing order lines get a price row', (await db.query(`select count(*)::int n from public.order_item_prices`)).rows[0].n === 1);
  ok('upgrade: business details row exists (empty)', (await db.query(`select business_name from public.business_settings`)).rows[0]?.business_name === '');
  ok('upgrade: former staff (now driver) can no longer write orders',
    !!(await as(db, 'driver', `insert into public.order_items (delivery_date, store_id, product_id, qty) values ('2026-01-06', 1, 1, 1)`)).error);
}

// ═══ B. Fresh install ════════════════════════════════════════════════════
const db = new PGlite();
await db.exec(SUPABASE_BASE);
await db.exec(`insert into auth.users (id, email) values ('${U.admin}', 'owner@example.com')`);
await db.exec(schema);
await db.exec(schema);  // re-run safe
for (const w of ['baker', 'driver', 'nobody']) await db.exec(`insert into auth.users (id, email) values ('${U[w]}', '${w}@example.com')`);
await db.exec(`update public.profiles set role = 'admin'  where id = '${U.admin}'`);
await db.exec(`update public.profiles set role = 'baker'  where id = '${U.baker}'`);
await db.exec(`update public.profiles set role = 'driver' where id = '${U.driver}'`);

const today = (await db.query(`select ((now() at time zone 'Australia/Sydney')::date)::text d`)).rows[0].d;
const yesterday = (await db.query(`select ((now() at time zone 'Australia/Sydney')::date - 1)::text d`)).rows[0].d;
const count = async (who, sql) => { const r = await as(db, who, `select count(*)::int n from (${sql}) x`); return r.error ? r.error : r.rows[0].n; };

ok('new account has no role', (await db.query(`select role from public.profiles where id = '${U.nobody}'`)).rows[0].role === null);
ok('no-role account sees no stores', await count('nobody', 'select * from public.stores') === 0);
ok('anon sees nothing', !!(await as(db, null, 'select * from public.stores')).error);

// Prices: normal 6 Pack $12, Uma Mart (7) pays $10
const upPrice = `insert into public.prices (product_id, store_id, price) values ($1, $2, $3)
                 on conflict (product_id, store_id) do update set price = excluded.price`;
ok('admin sets normal price', !(await as(db, 'admin', upPrice, [1, null, 12])).error);
ok('admin sets store special price', !(await as(db, 'admin', upPrice, [1, 7, 10])).error);
ok('upsert on normal price (store null) updates, not duplicates',
  !(await as(db, 'admin', upPrice, [1, null, 12])).error && (await db.query('select count(*)::int n from public.prices')).rows[0].n === 2);

// Orders
const upQty = `insert into public.order_items (delivery_date, store_id, product_id, qty) values ($1, $2, $3, $4)
               on conflict (delivery_date, store_id, product_id) do update set qty = excluded.qty`;
await as(db, 'admin', upQty, [today, 7, 1, 5]);
await as(db, 'admin', upQty, [today, 8, 1, 2]);
await as(db, 'admin', upQty, [yesterday, 8, 1, 1]);
await as(db, 'admin', upQty, [today, 8, 2, 3]);   // product without a price
const lp = async (date, s, p) => (await db.query(`select unit_price::float8 u from public.order_item_prices where delivery_date = $1 and store_id = $2 and product_id = $3`, [date, s, p])).rows[0]?.u;
ok('new line gets store special price', await lp(today, 7, 1) === 10);
ok('new line gets normal price', await lp(today, 8, 1) === 12);
ok('product without price -> null unit price', await lp(today, 8, 2) === null);
await as(db, 'admin', upQty, [today, 7, 1, 6]);
ok('qty change keeps one price row', (await db.query(`select count(*)::int n from public.order_item_prices where store_id = 7 and delivery_date = $1`, [today])).rows[0].n === 1);

// Price change: today follows, past stays
await as(db, 'admin', upPrice, [1, null, 13]);
ok('price change: today\'s line follows', await lp(today, 8, 1) === 13);
ok('price change: yesterday keeps old price', await lp(yesterday, 8, 1) === 12);
ok('price change: special-price store unaffected', await lp(today, 7, 1) === 10);
ok('removing special price -> line falls back to normal price',
  !(await as(db, 'admin', `delete from public.prices where product_id = 1 and store_id = 7`)).error && await lp(today, 7, 1) === 13);

// Amounts per stop (driver)
const amounts = async who => {
  const r = await as(db, who, `select store_id::int s, amount::float8 a from public.stop_amounts($1) order by 1`, [today]);
  return r.error ? r.error : JSON.stringify(r.rows);
};
ok('driver gets amount per stop (6×13, 2×13 + 3×no price)', await amounts('driver') === JSON.stringify([{ s: 7, a: 78 }, { s: 8, a: 26 }]), await amounts('driver'));
ok('admin gets amounts too', await amounts('admin') === await amounts('driver'));
ok('baker gets no amounts per stop', await amounts('baker') === '[]');
ok('no-role gets no amounts', await amounts('nobody') === '[]');

// Invoice lines per store (store_price_breakdown)
await as(db, 'admin', upPrice, [1, 7, 9.5]);  // special price again
const lines = async who => {
  const r = await as(db, who, `select store_id::int s, product_id::int p, qty q, unit_price::float8 u, amount::float8 a
    from public.store_price_breakdown($1) order by 1, 2`, [today]);
  return r.error ? r.error : JSON.stringify(r.rows);
};
const expectedLines = JSON.stringify([{ s: 7, p: 1, q: 6, u: 9.5, a: 57 }, { s: 8, p: 1, q: 2, u: 13, a: 26 }, { s: 8, p: 2, q: 3, u: null, a: 0 }]);
ok('baker gets invoice lines per store', await lines('baker') === expectedLines, await lines('baker'));
ok('driver gets invoice lines (prints invoices)', await lines('driver') === expectedLines);
ok('admin gets the same', await lines('admin') === expectedLines);
ok('no-role gets no invoice lines', await lines('nobody') === '[]');
ok('old breakdown functions removed',
  (await db.query(`select count(*)::int n from pg_proc where proname in ('product_amounts', 'product_price_breakdown')`)).rows[0].n === 0);
await as(db, 'admin', `delete from public.prices where product_id = 1 and store_id = 7`);

// Business details (invoices)
const bizSet = `update public.business_settings set business_name = $1, bsb = '123-456' where id = 1 returning id`;
ok('admin edits business details', (await as(db, 'admin', bizSet, ['GJ06'])).rows?.length === 1);
for (const who of ['baker', 'driver']) {
  ok(`${who} reads business details`, (await as(db, who, 'select business_name, bsb from public.business_settings')).rows?.[0]?.bsb === '123-456');
  const r = await as(db, who, bizSet, ['Hacked']);
  ok(`${who} cannot edit business details`, !r.error && r.rows.length === 0);
}
{
  const c = (await db.query(`select fuel_levy, freight_fee, freight_under from public.business_settings`)).rows[0];
  ok('delivery charges: fuel levy off, freight $5 under $50 by default', Number(c.fuel_levy) === 0 && Number(c.freight_fee) === 5 && Number(c.freight_under) === 50, c);
  ok('admin sets the fuel levy', !(await as(db, 'admin', `update public.business_settings set fuel_levy = 2 where id = 1`)).error);
  ok('driver reads the delivery charges', Number((await as(db, 'driver', 'select fuel_levy from public.business_settings')).rows?.[0]?.fuel_levy) === 2);
  ok('negative charge rejected', !!(await as(db, 'admin', `update public.business_settings set freight_fee = -1 where id = 1`)).error);
}
ok('no-role cannot read business details', await count('nobody', 'select * from public.business_settings') === 0);
ok('anon cannot read business details', !!(await as(db, null, 'select * from public.business_settings')).error);
ok('a second business row is impossible', !!(await as(db, 'admin', `insert into public.business_settings (id) values (2)`)).error
  && !!(await db.query(`insert into public.business_settings (id) values (2)`).catch(e => e)).message);
ok('business row cannot be deleted', !!(await as(db, 'admin', 'delete from public.business_settings')).error);
ok('business details unchanged by the attempts', (await db.query('select business_name from public.business_settings')).rows[0].business_name === 'GJ06');

// Store invoice details
ok('admin saves contact, phone and ABN',
  !(await as(db, 'admin', `update public.stores set contact_name = 'Sam Test', phone = '0412 345 678', abn = '12 345 678 901' where id = 3`)).error);
ok('ABN must be 11 digits', !!(await as(db, 'admin', `update public.stores set abn = '12345' where id = 3`)).error);
ok('driver sees store phone and ABN', (await as(db, 'driver', 'select phone, abn from public.stores where id = 3')).rows?.[0]?.abn === '12 345 678 901');
const sd = await as(db, 'driver', `update public.stores set phone = '000' where id = 3 returning id`);
ok('driver cannot change store details', !sd.error && sd.rows.length === 0);

// Driver: quantities yes, price tables no, writes no
ok('driver reads orders', await count('driver', 'select * from public.order_items') === 4);
ok('driver cannot read price list', await count('driver', 'select * from public.prices') === 0);
ok('driver cannot read payments', await count('driver', 'select * from public.deliveries') === 0);
ok('driver cannot read production', await count('driver', 'select * from public.production') === 0);
ok('driver cannot call effective_price', /permission denied/.test((await as(db, 'driver', 'select public.effective_price(7, 1)')).error || ''));
ok('driver cannot write orders', !!(await as(db, 'driver', upQty, [today, 7, 1, 99])).error);
ok('driver cannot set a price', !!(await as(db, 'driver', upPrice, [1, null, 1])).error);
ok('driver cannot record payment', !!(await as(db, 'driver', `insert into public.deliveries values ($1, 7, 'cash')`, [today])).error);

// Baker: production yes, payments no, order writes no
const upProd = `insert into public.production (production_date, product_id, qty_baked) values ($1, $2, $3)
                on conflict (production_date, product_id) do update set qty_baked = excluded.qty_baked`;
ok('baker records production', !(await as(db, 'baker', upProd, [today, 1, 40])).error && !(await as(db, 'baker', upProd, [today, 1, 42])).error);
ok('production stamped with baker', (await db.query('select updated_by from public.production')).rows[0].updated_by === U.baker);
ok('baker cannot read price list or payments', await count('baker', 'select * from public.prices') === 0 && await count('baker', 'select * from public.deliveries') === 0);
ok('baker cannot write orders', !!(await as(db, 'baker', upQty, [today, 7, 1, 99])).error);
ok('negative production rejected', !!(await as(db, 'baker', upProd, [today, 2, -1])).error);

// Payments (admin)
const upPay = `insert into public.deliveries (delivery_date, store_id, payment_mode) values ($1, $2, $3)
               on conflict (delivery_date, store_id) do update set payment_mode = excluded.payment_mode`;
ok('admin records cash, then online', !(await as(db, 'admin', upPay, [today, 7, 'cash'])).error && !(await as(db, 'admin', upPay, [today, 7, 'online'])).error);
ok('invalid payment mode rejected', !!(await as(db, 'admin', upPay, [today, 7, 'cheque'])).error);

// Profiles, routes, reorder, realtime
ok('nobody can promote themselves', !!(await as(db, 'driver', `update public.profiles set role = 'admin' where id = '${U.driver}'`)).error);
ok('admin moves a store to route 2', !(await as(db, 'admin', 'update public.stores set route = 2 where id = 8')).error);
ok('route must be 1 or 2', !!(await as(db, 'admin', 'update public.stores set route = 3 where id = 8')).error);
ok('driver cannot reorder', /Only admins/.test((await as(db, 'driver', 'select public.reorder_stores(array[2,1]::bigint[])')).error || ''));
ok('admin reorders', !(await as(db, 'admin', 'select public.reorder_stores(array[2,1]::bigint[])')).error);
const pub = (await db.query(`select string_agg(tablename, ',' order by tablename) t from pg_publication_tables where pubname = 'supabase_realtime'`)).rows[0].t;
ok('realtime on the 7 shared tables', pub === 'deliveries,order_item_prices,order_items,prices,production,products,stores', pub);

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
